"""
compare_dialogue_corpora.py — dialogue-level comparison of the dialogues generated by v1 (Elasticsearch
backend) and by v2 (local backend) for the same user–item pairs, paired by conv_id. Read-only; never calls
an API.

Part of the ES equivalence record. The v1 and v2 dialogue corpora that main() reads are not shipped with
this repository, so main() cannot be run as is. The script is kept because it documents how the two
backends were compared at the dialogue level, and because the tests use classify() and bot_turns().

Metrics, per group (imdb / imdb_fixture / hm / static) and overall:
  completion rate (and the pairs whose outcome differs), turns, recommendation attempts,
  MTLD / HDD / Distinct-1/2 (corpus level, with the functions of scripts/compute_nlp_metrics.py),
  failure reasons. MTLD depends on the order in which the dialogues are concatenated, Distinct-2 slightly
  (its bigrams cross utterance boundaries); Distinct-1 and HDD do not. Both corpora are concatenated in
  conv_id order, so v1's values differ from compute_nlp_metrics.py run on the folder (os.walk order):
  MTLD 92.57 vs 98.72, Distinct-2 0.5349 vs 0.5346, for the same 6,872 tokens. Expectation (report only; when exceeded, analyse why): completion rate within
  10 percentage points, mean turns within 1.

Turns / recommendation attempts / success come from the simulator's own counters in the final file
name ({user}-{item}-{turns}-{rec_attempts}-{succeed}-{ts}.txt): for v1 from the original file names listed
in <--v1>/README.md (checked against recordings/phase_a/conversations.jsonl), for v2 from <--v2>/map.jsonl.

Failure-reason rules — fixed from the 4 v1 failures before any v2 dialogue was generated
(A-imdb-6cec110e, A-imdb_static-02d32257 / -7cabb19b / -98618464: all end with the simulator's
<FAILED> "... not found within the maximum recommendation attempts" line after 6 attempts, and none of
them ever shows the target title). A dialogue ends with the simulator's <END> line or a <FAILED> System line.
  success                          the <END> line
  max_rec_attempts:target_not_shown  the <FAILED> line; the target title never appears in a bot turn
  max_rec_attempts:target_rejected   the <FAILED> line; the target title appears in a bot turn
  aborted                          the generation run hit the 10-minute limit (no final file); the
                                   tmp transcript and log are kept. Evidence of a loop (gate
                                   keeps failing after the questions run out → no recommendation, loop):
                                   the number of trailing bot turns without any quoted title and the
                                   number of recommendations in the tmp transcript. The report decides.
  max_total_rounds                 (added after the corpora were frozen; no frozen dialogue has it) the
                                   <FAILED> line written when the max_total_rounds stop-loss ends the dialogue
  incomplete                       a final file without either end line (should not happen)
  (infra_failed attempts — an LLM / embedding call raised — are not dialogue outcomes: they are left
  out of every statistic and only counted; the generation run retried the conversation)

Side-by-side export: the 4 v1 failures + 6 stratified random successes (seed 2025) → <--side-by-side>/<conv_id>.md.
Every pair whose outcome differs is listed in the tables, outside these 10.

Inputs (not shipped):
  --v1 DIR   <conv_id>.txt per conversation, and README.md whose table rows
             | <conv_id> | 0/1 | `<original file name>` | give the original file names
  --v2 DIR   map.jsonl, dialogues/<conv_id>.txt, aborted/ (output of the v2 generation run)

Usage:
    python legacy_es_equivalence/compare_dialogue_corpora.py --v1 <dir> --v1-only     # v1 statistics + rule self-check
    python legacy_es_equivalence/compare_dialogue_corpora.py --v1 <dir> --v2 <dir>    # full comparison
"""
import argparse
import collections
import json
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from scripts.compute_nlp_metrics import compute_distinct, compute_hdd, compute_ld_metrics, tokenize

CONVS = 'legacy_es_equivalence/recordings/phase_a/conversations.jsonl'
GROUPS = {'A-imdb': 'imdb', 'A-imdb_fixture': 'imdb_fixture', 'A-hm': 'hm', 'A-imdb_static': 'static'}
GROUP_ORDER = ['imdb', 'imdb_fixture', 'hm', 'static']
SIDE_BY_SIDE = ['A-imdb-6cec110e', 'A-imdb_static-02d32257', 'A-imdb_static-7cabb19b', 'A-imdb_static-98618464',
                'A-imdb-4355ae6b', 'A-imdb-f8bedd3d', 'A-imdb_fixture-b9bb84a1', 'A-hm-35fba456',
                'A-hm-df82babe', 'A-imdb_static-2afa5a34']
V1_FAILURES = {'A-imdb-6cec110e', 'A-imdb_static-02d32257', 'A-imdb_static-7cabb19b', 'A-imdb_static-98618464'}
EXPECT_COMPLETION_PP = 10.0
EXPECT_TURNS = 1.0

FINAL_NAME = re.compile(r'-(\d+)-(\d+)-([01])-(\d{14})\.txt$')
END_OK = re.compile(r"^System: <END> Session ended successfully\. The target item '(.*)' \((.*)\) was accepted")
END_FAIL = re.compile(r"^System: <FAILED> Session ended\. The target item '(.*)' \((.*)\) was not found within "
                      r"the maximum recommendation attempts\.")
END_ROUNDS = re.compile(r"^System: <FAILED> Session ended\. The target item '(.*)' \((.*)\) was not found before "
                        r"the dialogue round limit \(max_total_rounds\) was reached\.")
QUOTED = re.compile(r'"[^"]+"')


def read_jsonl(path):
    with open(path, encoding='utf-8') as f:
        return [json.loads(line) for line in f if line.strip()]


def counters_from_name(path):
    m = FINAL_NAME.search(os.path.basename(path))
    if not m:
        raise ValueError(f"not a final conversation file name: {path}")
    return {'turns': int(m.group(1)), 'rec_attempts': int(m.group(2)), 'succeed': int(m.group(3))}


def utterances(text):
    """Same rule as compute_nlp_metrics.load_utterances: the text after 'Bot:' / 'User:' line prefixes."""
    out = []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith('Bot:') or line.startswith('User:'):
            u = line.split(':', 1)[1].strip()
            if u:
                out.append(u)
    return out


def bot_turns(text):
    """Bot turns with their continuation lines (lines that start with no speaker prefix)."""
    turns, cur = [], None
    for line in text.splitlines():
        if line.startswith('Bot:'):
            cur = [line[4:].strip()]
            turns.append(cur)
        elif line.startswith(('User:', 'System:')):
            cur = None
        elif cur is not None:
            cur.append(line.strip())
    return [' '.join(t) for t in turns]


def classify(text, target_title=None):
    """(reason, target_title) by the fixed rules above, for a final file."""
    lines = [l for l in text.splitlines() if l.startswith('System:')]
    for l in lines:
        m = END_OK.match(l)
        if m:
            return 'success', m.group(1)
        m = END_FAIL.match(l)
        if m:
            title = m.group(1)
            shown = any(title.lower() in t.lower() for t in bot_turns(text))
            return ('max_rec_attempts:target_rejected' if shown else 'max_rec_attempts:target_not_shown'), title
        m = END_ROUNDS.match(l)
        if m:
            return 'max_total_rounds', m.group(1)
    return 'incomplete', target_title


def aborted_evidence(text):
    bots = bot_turns(text)
    trailing = 0
    for t in reversed(bots):
        if QUOTED.search(t):
            break
        trailing += 1
    return {'bot_turns': len(bots), 'user_turns': sum(l.startswith('User:') for l in text.splitlines()),
            'turns_with_quoted_title': sum(bool(QUOTED.search(t)) for t in bots),
            'trailing_bot_turns_without_title': trailing}


def load_v1(v1_dir):
    convs = {c['conv_id']: c for c in read_jsonl(CONVS)}
    src = {}
    with open(os.path.join(v1_dir, 'README.md'), encoding='utf-8') as f:
        for line in f:
            m = re.match(r'^\| (A-[^ ]+) \| [01] \| `([^`]+)` \|$', line.strip())
            if m:
                src[m.group(1)] = m.group(2)
    out, problems = {}, []
    for cid, c in convs.items():
        text = open(os.path.join(v1_dir, f'{cid}.txt'), encoding='utf-8').read()
        k = counters_from_name(src[cid])
        if (k['turns'], k['rec_attempts'], k['succeed']) != (c['number_turns'], c['rec_attempts'], c['succeed']):
            problems.append(f"{cid}: file name counters {k} != conversations.jsonl")
        reason, title = classify(text)
        if (reason == 'success') != bool(k['succeed']):
            problems.append(f"{cid}: end line {reason} but succeed={k['succeed']}")
        out[cid] = {'conv_id': cid, 'group': GROUPS[c['label']], 'status': 'completed', 'text': text,
                    'reason': reason, 'target_title': title, **k}
    return out, problems


def load_v2(v2_dir, v1):
    """(dialogues, problems, infra_failed attempts per conv). infra_failed entries (an LLM / embedding call
    raised during the generation run) are not dialogue outcomes and are left out of the comparison."""
    out, problems, infra = {}, [], collections.Counter()
    for rec in read_jsonl(os.path.join(v2_dir, 'map.jsonl')):
        cid = rec['conv_id']
        if rec['status'] == 'infra_failed':
            infra[cid] += 1
            continue
        if cid in out:
            problems.append(f"{cid}: several map.jsonl entries (the last one is used)")
        base = {'conv_id': cid, 'group': v1[cid]['group'], 'status': rec['status']}
        if rec['status'] == 'aborted':
            tmp = [os.path.join(v2_dir, 'aborted', f"{cid}.{os.path.basename(t)}") for t in rec.get('tmp_files', [])]
            text = open(tmp[0], encoding='utf-8').read() if tmp and os.path.exists(tmp[0]) else ''
            out[cid] = {**base, 'text': text, 'reason': 'aborted', 'turns': None, 'rec_attempts': None,
                        'succeed': 0, 'duration_s': rec['duration_s'], 'evidence': aborted_evidence(text),
                        'n_tmp_files': len(tmp), 'target_title': v1[cid]['target_title']}
            continue
        text = open(os.path.join(v2_dir, 'dialogues', f'{cid}.txt'), encoding='utf-8').read()
        k = counters_from_name(rec['src'])
        reason, title = classify(text, v1[cid]['target_title'])
        if (reason == 'success') != bool(k['succeed']):
            problems.append(f"{cid}: end line {reason} but succeed={k['succeed']}")
        out[cid] = {**base, 'text': text, 'reason': reason, 'target_title': title,
                    'duration_s': rec['duration_s'], **k}
    return out, problems, dict(infra)


def corpus_metrics(dialogues):
    utts = [u for d in sorted(dialogues, key=lambda d: d['conv_id']) for u in utterances(d['text'])]
    tokens = [t for u in utts for t in tokenize(u)]
    d1, d2 = compute_distinct(utts)
    ld = compute_ld_metrics(tokens) if tokens else {}
    return {'n_utterances': len(utts), 'n_tokens': len(tokens), 'distinct_1': round(d1, 4),
            'distinct_2': round(d2, 4), 'hdd': round(compute_hdd(tokens), 4),
            'mtld': round(ld['mtld'], 4) if 'mtld' in ld else None}


def side_stats(dialogues):
    n = len(dialogues)
    done = [d for d in dialogues if d['status'] == 'completed']
    succ = sum(d['succeed'] for d in done)
    mean = lambda xs: round(sum(xs) / len(xs), 3) if xs else None
    return {'n': n, 'aborted': n - len(done), 'succeeded': succ,
            'completion_rate': round(succ / n, 4) if n else None,
            'mean_turns': mean([d['turns'] for d in done]),
            'mean_rec_attempts': mean([d['rec_attempts'] for d in done]),
            'reasons': dict(sorted(collections.Counter(d['reason'] for d in dialogues).items())),
            **corpus_metrics(dialogues)}


def fmt(x, nd=3):
    return '-' if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--v1', required=True, help='directory of the v1 dialogues (not shipped; see the docstring)')
    ap.add_argument('--v2', help='directory of the v2 generation run (not shipped; see the docstring)')
    ap.add_argument('--out', default='results/dialogue_compare', help='summary.json + tables.md')
    ap.add_argument('--side-by-side', default='results/dialogue_compare/side_by_side')
    ap.add_argument('--v1-only', action='store_true', help='v1 statistics and the rule self-check only')
    args = ap.parse_args()
    if not args.v1_only and not args.v2:
        ap.error('--v2 is required unless --v1-only')

    v1, problems = load_v1(args.v1)
    v1_fail = {cid: d['reason'] for cid, d in v1.items() if d['reason'] != 'success'}
    print(f"v1: {len(v1)} dialogues; failures {len(v1_fail)}: {v1_fail}")
    if set(v1_fail) != V1_FAILURES or set(v1_fail.values()) != {'max_rec_attempts:target_not_shown'}:
        problems.append(f"rule self-check: v1 failures classify as {v1_fail}, expected {sorted(V1_FAILURES)} "
                        "all max_rec_attempts:target_not_shown")
    if args.v1_only:
        st = side_stats(list(v1.values()))
        print(json.dumps(st, ensure_ascii=False))
        for g in GROUP_ORDER:
            print(g, json.dumps(side_stats([d for d in v1.values() if d['group'] == g]), ensure_ascii=False))
        for p in problems:
            print('PROBLEM', p)
        return 1 if problems else 0

    v2, p2, infra = load_v2(args.v2, v1)
    problems += p2
    missing = sorted(set(v1) - set(v2))
    if missing:
        problems.append(f"{len(missing)} conversations have no v2 result: {missing[:10]}")
    paired = [cid for cid in sorted(v1) if cid in v2]

    summary = {'n_pairs': len(paired), 'missing_v2': missing, 'infra_failed_attempts': infra,
               'groups': {}, 'problems': problems}
    for g in ['all'] + GROUP_ORDER:
        ids = [c for c in paired if g == 'all' or v1[c]['group'] == g]
        s1, s2 = side_stats([v1[c] for c in ids]), side_stats([v2[c] for c in ids])
        both = [c for c in ids if v2[c]['status'] == 'completed']
        summary['groups'][g] = {
            'v1': s1, 'v2': s2,
            'outcome_differs': [c for c in ids if v1[c]['succeed'] != v2[c]['succeed']],
            'paired_mean_turn_diff': (round(sum(v2[c]['turns'] - v1[c]['turns'] for c in both) / len(both), 3)
                                      if both else None)}
    allg = summary['groups']['all']
    d_comp = 100 * (allg['v2']['completion_rate'] - allg['v1']['completion_rate'])
    d_turns = (allg['v2']['mean_turns'] - allg['v1']['mean_turns']
               if allg['v2']['mean_turns'] is not None else None)
    p = allg['v1']['completion_rate']
    summary['expectation'] = {
        'completion_rate_diff_pp': round(d_comp, 2), 'within_10pp': abs(d_comp) < EXPECT_COMPLETION_PP,
        'mean_turns_diff': None if d_turns is None else round(d_turns, 3),
        'within_1_turn': d_turns is not None and abs(d_turns) < EXPECT_TURNS,
        'se_completion_rate_pp_v1': round(100 * math.sqrt(p * (1 - p) / allg['v1']['n']), 2),
        'note': 'one sample per pair; v1 LLM noise cannot be measured after ES is removed'}
    summary['aborted'] = {c: {k: v2[c][k] for k in ('duration_s', 'n_tmp_files', 'evidence')}
                          for c in paired if v2[c]['status'] == 'aborted'}

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, 'summary.json'), 'w', encoding='utf-8') as f:
        json.dump(summary, f, indent=1, ensure_ascii=False)
    rows = ['| group | side | n | completed | rate | aborted | turns | recs | D-1 | D-2 | HDD | MTLD | reasons |',
            '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for g, G in summary['groups'].items():
        for side in ('v1', 'v2'):
            s = G[side]
            rows.append(f"| {g} | {side} | {s['n']} | {s['succeeded']} | {fmt(s['completion_rate'])} | {s['aborted']} "
                        f"| {fmt(s['mean_turns'])} | {fmt(s['mean_rec_attempts'])} | {fmt(s['distinct_1'], 4)} "
                        f"| {fmt(s['distinct_2'], 4)} | {fmt(s['hdd'], 2)} | {fmt(s['mtld'], 2)} "
                        f"| {', '.join(f'{k} {v}' for k, v in s['reasons'].items())} |")
    diff_rows = ['| conv_id | group | v1 | v2 | v1 turns/recs | v2 turns/recs |', '|---|---|---|---|---|---|']
    for c in allg['outcome_differs']:
        diff_rows.append(f"| {c} | {v1[c]['group']} | {v1[c]['reason']} | {v2[c]['reason']} "
                         f"| {v1[c]['turns']}/{v1[c]['rec_attempts']} | {fmt(v2[c]['turns'])}/{fmt(v2[c]['rec_attempts'])} |")
    e = summary['expectation']
    md = ['# Dialogue-level comparison v1 (ES) vs v2 (local) — generated by legacy_es_equivalence/compare_dialogue_corpora.py', '',
          f"pairs {len(paired)}, missing v2 {len(missing)}, aborted {len(summary['aborted'])}; "
          f"infrastructure-failed attempts (not counted) {sum(infra.values())} in {len(infra)} conversations"
          + (f": {infra}" if infra else ''), '',
          *rows, '',
          f"completion rate difference {e['completion_rate_diff_pp']:+.2f} pp (expectation |Δ| < 10: "
          f"{'within' if e['within_10pp'] else 'EXCEEDED — analyse'}); mean turns difference {fmt(e['mean_turns_diff'])} "
          f"(expectation |Δ| < 1: {'within' if e['within_1_turn'] else 'EXCEEDED — analyse'}); "
          f"SE of the v1 completion rate ≈ {e['se_completion_rate_pp_v1']} pp; {e['note']}", '',
          '## Pairs whose outcome differs', '', *diff_rows, '',
          '## Aborted (time limit)', '',
          *[f"- {c}: {v['duration_s']} s, tmp files {v['n_tmp_files']}, {v['evidence']}"
            for c, v in summary['aborted'].items()], '',
          '## Problems', '', *[f"- {p}" for p in problems]]
    with open(os.path.join(args.out, 'tables.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(md) + '\n')

    os.makedirs(args.side_by_side, exist_ok=True)
    for c in SIDE_BY_SIDE:
        if c not in v2:
            continue
        a, b = v1[c], v2[c]
        doc = [f"# {c} ({a['group']}) — v1 (ES) vs v2 (local)", '',
               '| | v1 | v2 |', '|---|---|---|',
               f"| outcome | {a['reason']} | {b['reason']} |",
               f"| turns / recommendation attempts | {a['turns']} / {a['rec_attempts']} | {fmt(b['turns'])} / {fmt(b['rec_attempts'])} |",
               f"| target | {a['target_title']} | {b['target_title']} |", '',
               '## v1', '', '```text', a['text'].rstrip('\n'), '```', '',
               '## v2', '', '```text', (b['text'] or '(no transcript)').rstrip('\n'), '```']
        with open(os.path.join(args.side_by_side, f'{c}.md'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(doc) + '\n')

    print('\n'.join(md[:len(rows) + 6]))
    for p in problems:
        print('PROBLEM', p)
    print(f"wrote {args.out}/summary.json, {args.out}/tables.md, {args.side_by_side}/ "
          f"({sum(c in v2 for c in SIDE_BY_SIDE)} files)")
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
