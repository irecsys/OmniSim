"""
make_fixture_pairs.py — Build the input pair sets used to record the v1 dialogues (v2 migration).

Writes
  <out-dir>/imdb_pairs.csv          IMDB free mode: profiled users first block, unprofiled second
  <out-dir>/imdb_static_pairs.csv   IMDB static mode (profiled users)
  <out-dir>/imdb_fixture_pairs.csv  imdb_fixture free mode (synthetic recent interactions → β>0)
  <out-dir>/hm_pairs.csv            H&M free mode (all α=1: the H&M user profiles are empty)
  <out-dir>/selection.json          seed, group sizes, ordering rule
and, unless it already exists, the fixture-only dataset
  data/imdb_fixture/{users.csv, interactions.csv, imdb_fixture.yaml}

Every list is the full eligible pool in a seeded random order, so a run of N
conversations takes the first N rows (recording scripts pass --limit). The IMDB
list interleaves profiled / unprofiled users 3:1 so any prefix keeps that ratio.

No LLM / embedding calls. data/imdb/ is only read.

Usage:
    python legacy_es_equivalence/make_fixture_pairs.py --out-dir legacy_es_equivalence/recordings/inputs
"""
import argparse
import json
import os
import random
from datetime import datetime, timedelta

import pandas as pd

SEED = 2025
FIXTURE_USERS = ['u1', 'u2', 'u9', 'u11', 'u14']   # ≥2 liked items each (rating > 3)
RATING_THRESHOLD = 3                               # system.yaml rating_threshold
FIXTURE_DIR = 'data/imdb_fixture'

FIXTURE_YAML = """\
# imdb_fixture — fixture-only dataset for the v2 migration (S2). Not a real dataset.
# Same items / ES index as IMDB; 5 users whose interactions were partly moved into
# the last few days, so the short-term profile differs from the long-term one (β>0).
# Generated by scripts/make_fixture_pairs.py. Use after configs/imdb/imdb.yaml:
#   --config "configs/system/system.yaml configs/imdb/imdb.yaml data/imdb_fixture/imdb_fixture.yaml"
dataset: imdb_fixture
file_items: ../imdb/items.csv
file_users: users.csv
file_interactions: interactions.csv
"""


def shuffled(rows, rng):
    rows = list(rows)
    rng.shuffle(rows)
    return rows


def build_fixture_dataset(rng, now):
    users = pd.read_csv('data/imdb/users.csv')
    inter = pd.read_csv('data/imdb/interactions.csv')
    os.makedirs(FIXTURE_DIR, exist_ok=False)

    users[users.user_id.isin(FIXTURE_USERS)].to_csv(os.path.join(FIXTURE_DIR, 'users.csv'), index=False)

    out = inter[inter.user_id.isin(FIXTURE_USERS)].copy()
    moved = {}
    for uid in FIXTURE_USERS:
        liked = out[(out.user_id == uid) & (out.vote_average > RATING_THRESHOLD)].index.tolist()
        k = max(1, len(liked) // 2)          # move only part of the liked items → short ≠ long
        chosen = rng.sample(liked, k)
        for idx in chosen:
            out.loc[idx, 'timestamp'] = (now - timedelta(days=rng.randint(1, 5))).strftime('%Y-%m-%d')
        moved[uid] = {'liked': len(liked), 'moved_recent': out.loc[chosen, 'imdb_id'].tolist()}
    out.to_csv(os.path.join(FIXTURE_DIR, 'interactions.csv'), index=False)

    with open(os.path.join(FIXTURE_DIR, 'imdb_fixture.yaml'), 'w', encoding='utf-8') as f:
        f.write(FIXTURE_YAML)
    return moved


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-dir', required=True)
    args = ap.parse_args()
    rng = random.Random(SEED)
    now = datetime.now()

    if os.path.exists(FIXTURE_DIR):
        moved = None
        print(f"{FIXTURE_DIR} exists — left untouched (delete it by hand to regenerate)")
    else:
        moved = build_fixture_dataset(rng, now)
        print(f"wrote {FIXTURE_DIR}/ (users.csv, interactions.csv, imdb_fixture.yaml)")
    rng = random.Random(SEED + 1)        # pair order must not depend on whether the dataset was built

    profiles = pd.read_csv('data/imdb/user_profiles.csv')
    profiled = set(profiles.loc[profiles.user_likes_long.notna(), 'userid'])
    imdb_pairs = pd.read_csv('configs/imdb/inputs/test_pairs.csv')
    rows = imdb_pairs.to_dict('records')
    prof_rows = shuffled([r for r in rows if r['user_id'] in profiled], rng)
    unprof_rows = shuffled([r for r in rows if r['user_id'] not in profiled], rng)

    # static gets its own profiled pairs, disjoint from the free list
    static_rows, prof_rows = prof_rows[:20], prof_rows[20:]
    interleaved = []
    while prof_rows or unprof_rows:
        interleaved += [prof_rows.pop(0) for _ in range(3) if prof_rows]
        if unprof_rows:
            interleaved.append(unprof_rows.pop(0))

    fixture_rows = shuffled([r for r in rows if r['user_id'] in FIXTURE_USERS], rng)
    hm_rows = shuffled(pd.read_csv('configs/hm/inputs/test_pairs.csv').to_dict('records'), rng)

    os.makedirs(args.out_dir, exist_ok=True)
    lists = {'imdb_pairs.csv': interleaved, 'imdb_static_pairs.csv': static_rows,
             'imdb_fixture_pairs.csv': fixture_rows, 'hm_pairs.csv': hm_rows}
    for name, rws in lists.items():
        pd.DataFrame(rws, columns=['user_id', 'item_id']).to_csv(os.path.join(args.out_dir, name), index=False)
        print(f"wrote {args.out_dir}/{name} ({len(rws)} rows)")

    with open(os.path.join(args.out_dir, 'selection.json'), 'w', encoding='utf-8') as f:
        json.dump({'seed': SEED, 'generated': now.isoformat(timespec='seconds'),
                   'profiled_users': sorted(profiled, key=lambda u: int(u[1:])),
                   'fixture_users': FIXTURE_USERS, 'fixture_moved_recent': moved,
                   'rule': 'full eligible pool in seeded order; runs take a prefix (--limit). '
                           'imdb_pairs interleaves profiled:unprofiled = 3:1.'}, f, indent=2)


if __name__ == '__main__':
    main()
